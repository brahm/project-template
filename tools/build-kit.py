#!/usr/bin/env python3
"""Rebuilds what the kit derives from the template.

Usage: tools/build-kit.py [--check]

Each skill of project-template/.claude/skills is zipped into
desktop/claude-skills/NAME.zip, the form Claude desktop takes as an upload.
A zip whose skill no longer exists is removed. The zips are built the same
way every time (fixed dates, sorted entries), so a rebuild without a change
to a skill changes no file.

The automatic review of the template (.github/workflows/review.yml) is
also copied to the kit's own .github/workflows/review.yml, with the paths
of the kit, so that the kit's pull requests are reviewed the same way.

--check builds nothing: it fails when a zip or the review workflow is
missing, stale or left over, which is how tools/test-kit.sh and the CI
notice that a skill or the workflow was edited without running this
script. A zip is compared by the names and contents of its files, not by
its bytes, which another version of zlib compresses differently.
"""
import io
import pathlib
import sys
import zipfile

KIT = pathlib.Path(__file__).resolve().parent.parent
SKILLS = KIT / 'project-template' / '.claude' / 'skills'
ZIPS = KIT / 'desktop' / 'claude-skills'
EPOCH = (1980, 1, 1, 0, 0, 0)       # the earliest date a zip can hold
REVIEW = KIT / 'project-template' / '.github' / 'workflows' / 'review.yml'
KIT_REVIEW = KIT / '.github' / 'workflows' / 'review.yml'
# What changes from the template's review to the kit's: the paths of the
# template's pages and script, and the language of the owner.
KIT_PATHS = [
    ('# Reviews every pull request', '# Generated by tools/build-kit.py from project-template/.github/workflows/review.yml:\n'
     '# edit that file and run the script.\n#\n# Reviews every pull request'),
    ('docs/kit.md', 'project-template/docs/kit.md'),
    ('docs/engineering.md', 'project-template/docs/engineering.md'),
    ('docs/specs', 'project-template/docs/specs'),
    ('docs/decisions.md', 'project-template/docs/decisions.md'),
    ('scripts/review-report.py', 'project-template/scripts/review-report.py'),
    ('{{OWNER_LANGUAGE}}', 'Brazilian Portuguese'),
]


def build(skill):
    """The bytes of the zip of one skill folder: the folder, then its files in order."""
    data = io.BytesIO()
    with zipfile.ZipFile(data, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        folder = zipfile.ZipInfo(skill.name + '/', EPOCH)
        folder.external_attr = (0o40755 << 16) | 0x10
        z.writestr(folder, b'')
        for path in sorted(p for p in skill.rglob('*') if p.is_file()):
            info = zipfile.ZipInfo(f'{skill.name}/{path.relative_to(skill).as_posix()}', EPOCH)
            info.external_attr = 0o100644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, path.read_bytes(), compresslevel=9)
    return data.getvalue()


def contents(data):
    """The names and contents of the files of a zip, or None when it is not a zip."""
    try:
        with zipfile.ZipFile(io.BytesIO(data)) as z:
            return sorted((i.filename, z.read(i)) for i in z.infolist())
    except zipfile.BadZipFile:
        return None


def kit_review():
    """The text of the kit's review workflow, made from the template's."""
    text = REVIEW.read_text(encoding='utf-8')
    for old, new in KIT_PATHS:
        if old not in text:
            sys.exit(f'tools/build-kit.py: "{old}" is no longer in {REVIEW.relative_to(KIT)}; update KIT_PATHS')
        text = text.replace(old, new)
    return text


def main(argv):
    if argv not in ([], ['--check']):
        sys.exit(__doc__)
    check = bool(argv)
    wanted = {s.name + '.zip': build(s) for s in sorted(SKILLS.iterdir()) if (s / 'SKILL.md').is_file()}
    have = {p.name for p in ZIPS.glob('*.zip')}
    problems = []
    for name, data in wanted.items():
        path = ZIPS / name
        if not path.exists() or contents(path.read_bytes()) != contents(data):
            if check:
                problems.append(f'desktop/claude-skills/{name} is {"stale" if path.exists() else "missing"}')
            else:
                path.write_bytes(data)
                print(f'wrote desktop/claude-skills/{name}')
    for name in sorted(have - set(wanted)):
        if check:
            problems.append(f'desktop/claude-skills/{name} has no skill any more')
        else:
            (ZIPS / name).unlink()
            print(f'removed desktop/claude-skills/{name}')
    review = kit_review()
    if not KIT_REVIEW.exists() or KIT_REVIEW.read_text(encoding='utf-8') != review:
        if check:
            problems.append(f'.github/workflows/review.yml is {"stale" if KIT_REVIEW.exists() else "missing"}')
        else:
            KIT_REVIEW.write_text(review, encoding='utf-8')
            print('wrote .github/workflows/review.yml')
    if problems:
        print('\n'.join(problems), file=sys.stderr)
        sys.exit('Run tools/build-kit.py and commit what it writes.')
    print(f'{len(wanted)} skill zips and the review workflow are current')


if __name__ == '__main__':
    main(sys.argv[1:])
